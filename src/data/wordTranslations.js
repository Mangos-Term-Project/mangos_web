const PARTS = ['noun', 'verb', 'adjective']

// Every Spanish translation for a word, one per part of speech it belongs to.
export function getSpanishTranslations(word) {
	const key = typeof word === 'string' ? word.trim().toLowerCase() : ''
	if (!key) return []
	return PARTS
		.filter((part) => Object.hasOwn(wordTranslations[part], key))
		.map((part) => ({ partOfSpeech: part, spanish: wordTranslations[part][key] }))
}
