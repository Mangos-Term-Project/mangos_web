// Returns every hint for a word, in noun/verb/adjective order.
// Pass partOfSpeech to narrow it once the API provides one.
export function getWordHints(word, partOfSpeech) {
	const key = typeof word === 'string' ? word.trim().toLowerCase() : ''
	if (!key) return []
	const parts = partOfSpeech ? [partOfSpeech] : PARTS_OF_SPEECH
	return parts
		.filter((part) => Object.hasOwn(wordHints, part) && Object.hasOwn(wordHints[part], key))
		.map((part) => ({ partOfSpeech: part, ...wordHints[part][key] }))
}
